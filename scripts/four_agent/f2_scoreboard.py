"""Fixed six-block F2 own-output scoreboard. No launch, retries or optional stopping."""
import math
import statistics

ORDERS = ("ABC", "BCA", "CAB", "CBA", "BAC", "ACB")
T5 = 2.5705818366
SCHEMA = "hf2q.f2.fixed-six-scoreboard.v1"


def require(ok, why):
    if not ok:
        raise ValueError(why)


def effect(blocks, numerator, denominator):
    differences = [math.log(b[numerator] / b[denominator]) for b in blocks]
    mean = statistics.mean(differences)
    radius = T5 * statistics.stdev(differences) / math.sqrt(6)
    point = 100 * -math.expm1(mean)
    interval = [100 * -math.expm1(mean + radius), 100 * -math.expm1(mean - radius)]
    half = (interval[1] - interval[0]) / 2
    return {"block_log_ratios": differences, "geometric_ratio": math.exp(mean),
            "reduction_percent": point, "nominal_pointwise_ci95_percent": interval,
            "halfwidth_percentage_points": half, "precision_met": half <= 2.5,
            "assumption": "independent approximately normal block log-ratios; Student-t df5"}


def paired_scoreboard(plan, cohorts):
    require(plan.get("schema") == SCHEMA and plan.get("fixed_blocks") == 6 and
            plan.get("orders") == list(ORDERS) and plan.get("optional_extension") is False and
            plan.get("primary") == "own_output_four_successful_task_makespan" and
            plan.get("precision_halfwidth_pp") == 2.5 and
            plan.get("sampling_lane") == "captured_production_client" and
            set(plan.get("production_client_profile", {})) == {"path", "sha256"},
            "reviewed fixed-six predeclaration required")
    require(set(plan["arms"]) == {"A", "B", "C"} and len(cohorts) == 18,
            "three bound arms and all eighteen retained cohorts required")
    require(len({c["cohort_id"] for c in cohorts}) == 18, "duplicate cohort")
    blocks = [{} for _ in range(6)]
    invalid, quality = [], []
    retained = []
    for index, c in enumerate(cohorts):
        block, position = divmod(index, 3)
        arm = ORDERS[block][position]
        require(c["block_index"] == block and c["position"] == position and c["arm"] == arm,
                "fixed order mismatch; no sorting or replacement")
        require(c["identity"] == plan["arms"][arm], "source/profile/model arm drift")
        require(type(c["started_ns"]) is int and type(c["finished_ns"]) is int and
                0 <= c["started_ns"] < c["finished_ns"], "measured cohort clock")
        duration = (c["finished_ns"] - c["started_ns"]) / 1e9
        require(math.isfinite(duration) and duration > 0, "positive cohort duration")
        # Certification is externally generated by the actual Q2 raw-artifact auditor.
        # A CLI must re-run that auditor; a self-reported quality_pass is never accepted.
        certificate = c["certification"]
        require(certificate.get("schema") == "hf2q.q2.certification.v1" and
                certificate["cohort_id"] == c["cohort_id"] and
                certificate["identity"] == c["identity"] and
                certificate["required_cardinality"] == 4 and certificate.get("verified_refs") and
                certificate.get("sampling_lane") == "captured_production_client" and
                certificate.get("profile_sha256") == c["identity"]["profile_sha256"],
                "bound four-task raw certification required; N1 is not a primary cohort")
        require(c["started_ns"] == certificate["makespan_started_ns"] and
                c["finished_ns"] == certificate["makespan_finished_ns"],
                "primary clocks must join raw barrier release and four validated task completions")
        status = certificate["status"]
        if status != "Qualified":
            (quality if certificate.get("failure_class") == "quality" else invalid).append(c["cohort_id"])
        if c.get("trace_status") != "Qualified":
            invalid.append(c["cohort_id"])
        retained.append({"cohort_id": c["cohort_id"], "block": block, "arm": arm,
                         "makespan_seconds": duration, "certification_status": status})
        blocks[block][arm] = duration
    result = {"schema": SCHEMA, "cohorts": retained, "fixed_blocks": 6,
              "calculation_only": True, "raw_certification_performed": False,
              "speed_win_claim": False,
              "statistical_unit": "four-successful-task cohort; paired block log ratio",
              "whole_campaign_invalid_cohorts": invalid, "quality_ineligible_cohorts": quality,
              "primary": None, "secondary": None, "joint_four_family_coverage_claim": False}
    if invalid or quality:
        result["status"] = "InvalidCampaign" if invalid else "QualityIneligible"
        return result
    primary = effect(blocks, "B", "A")
    peer = effect(blocks, "B", "C")
    result.update(primary=primary, secondary={"B_over_C": peer,
                                             "A_over_C": effect(blocks, "A", "C")},
                  primary_precision_met=primary["precision_met"], peer_precision_met=peer["precision_met"],
                  status="Qualified" if primary["precision_met"] and peer["precision_met"]
                  else "InconclusivePrecision")
    return result
